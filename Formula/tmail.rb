  depends_on "himalaya"

  url "https://github.com/jodaka/tmail/releases/download/v#{version}/tmail-v#{version}-aarch64-apple-darwin.tar.gz"
  sha256 "7aa7c7e61f99a6833ca48dac51c0cc3f121d3a049baa719a75e8ce445269c0d2"

  on_macos do
