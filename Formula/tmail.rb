      url "https://github.com/jodaka/tmail/releases/download/v#{version}/tmail-v#{version}-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "7361cb34c0ebb3a812f8ecee128529a9db92084a930ae635df2c9f298fbc14f8"
    end
  end

  def install
