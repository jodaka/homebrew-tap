    end
  end

  on_linux do
    on_intel do
      url "https://github.com/jodaka/tmail/releases/download/v#{version}/tmail-v#{version}-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "b663a576db11f6bb2750081aaac4e2cf33f068c5642d81e1cab4720398bb6f38"
    end
